import { mkdir,readFile,writeFile,access } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { git } from '../lib/process.mjs';
import { newState,investigate } from '../lib/engine.mjs';
import { checkReadiness } from '../lib/doctor.mjs';
import { verifyFix } from '../lib/verify-fix.mjs';
import { markdownReport } from '../lib/ai.mjs';
import { issueReport } from '../lib/issue-report.mjs';
const root=fileURLToPath(new URL('../',import.meta.url));
const repo=process.argv[2]?path.resolve(process.argv[2]):path.join(root,'.data','realworld','clsx');
await mkdir(path.dirname(repo),{recursive:true});
try{await access(path.join(repo,'.git'));}catch{await git(path.dirname(repo),['clone','--no-checkout','https://github.com/lukeed/clsx.git',repo],{timeout:120000});}
const config={repo,good:'6da37d67472ea9eb177a4ea9a9fa2f3f4a3c445e',bad:'6232a9e5649143a28419a04f786a15f63a0b7edd',repeats:2,timeoutMs:10000,failurePattern:'PACKAGE_MANIFEST_ACCESS',reproScript:await readFile(new URL('../examples/clsx-package-exports-check.mjs',import.meta.url),'utf8')};
const readiness=await checkReadiness(config,newState(randomUUID()));
if(readiness.doctor.verdict!=='ready')throw new Error('Real-world readiness failed: '+readiness.error);
let last='';
const state=await investigate(config,newState(randomUUID()),s=>{if(s.phase!==last){console.log(s.phase);last=s.phase;}});
const expected='3ec8e9fa2f6eef3911cb47f656ab761fc1030812';
if(state.result?.candidate!==expected)throw new Error('The historical boundary was not identified: '+state.error);
const oldManifest=(await git(repo,['show',`${expected}:package.json`])).stdout;
const manifest=JSON.parse(oldManifest);
manifest.exports={'.':manifest.exports,'./package.json':'./package.json'};
const newManifest=JSON.stringify(manifest,null,2)+'\n';
const oldLines=oldManifest.trimEnd().split('\n'),newLines=newManifest.trimEnd().split('\n');
const patch=`diff --git a/package.json b/package.json\n--- a/package.json\n+++ b/package.json\n@@ -1,${oldLines.length} +1,${newLines.length} @@\n`+oldLines.map(line=>'-'+line).join('\n')+'\n'+newLines.map(line=>'+'+line).join('\n')+'\n';
state.verification=await verifyFix(state,{patch});
if(state.verification.status!=='passed')throw new Error('Proposed compatibility patch did not pass: '+state.verification.message);
state.realWorld={repository:'https://github.com/lukeed/clsx',upstreamCommit:`https://github.com/lukeed/clsx/commit/${expected}`,kind:'Reconstructed downstream compatibility check against real public history',note:'The upstream change was explicitly intentional and marked breaking. This is not a newly discovered vulnerability or an invented user incident. The probe copies only the historical manifest into a minimal package layout and uses Node package resolution; upstream scripts are not executed.'};
const reports=path.join(root,'.data','reports');await mkdir(reports,{recursive:true});
await writeFile(path.join(reports,state.id+'.json'),JSON.stringify(state));
await writeFile(path.join(root,'evidence','real-world-case.json'),JSON.stringify(state,null,2));
await writeFile(path.join(root,'evidence','real-world-case.md'),markdownReport(state));
await writeFile(path.join(root,'evidence','real-world-issue.md'),issueReport(state));
await writeFile(path.join(root,'.data','real-world-fix.patch'),patch);
await writeFile(path.join(root,'evidence','real-world-readiness.json'),JSON.stringify(readiness,null,2));
console.log(JSON.stringify({caseId:state.id,history:state.result.historySize,checks:state.result.checks,candidate:state.result.candidate,elapsedMs:state.elapsedMs,fix:state.verification.status,fixExecutions:state.verification.runs.length,notice:state.realWorld.note},null,2));
